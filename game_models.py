# Player
# ---------------------------------------------------------------------------


def decode_name(name) -> str:
    """Normalize a player name that may carry UTF-16 encoding artifacts.

    Source rows sometimes arrive with the name still UTF-16 encoded (raw bytes)
    or with lingering surrogate code points from a bad decode. This coerces
    such values back to a clean Python str; already-clean names pass through
    unchanged.
    """
    if name is None:
        return ""
    # Raw bytes: use the BOM to pick UTF-16, else UTF-8. (Auto-guessing UTF-16
    # vs UTF-8 without a BOM is unreliable — UTF-16 "succeeds" on UTF-8 bytes
    # and yields garbage — so we only treat BOM-prefixed data as UTF-16.)
    if isinstance(name, (bytes, bytearray)):
        data = bytes(name)
        if data[:2] in (b"\xff\xfe", b"\xfe\xff"):
            name = data.decode("utf-16")
        else:
            name = data.decode("utf-8", errors="replace")
    # Repair any unpaired/paired surrogate code points left in a str by
    # re-encoding as UTF-16 and decoding back.
    if isinstance(name, str) and any(0xD800 <= ord(ch) <= 0xDFFF for ch in name):
        name = name.encode("utf-16", "surrogatepass").decode("utf-16")
    return name


@dataclass
class Player:
    """A single MLB player. Only identity fields are used by the game."""

    name: str
    team: str = ""
    position: str = ""
    war: float | None = None
    age: int | None = None
    awards: str = ""
    games: int | None = None
    home_runs: int | None = None
    batting_avg: float | None = None
    on_base_pct: float | None = None
    slugging: float | None = None
    ops: float | None = None

    @classmethod
    def from_record(cls, record: dict) -> "Player":
        """Build a Player from one row of Data/MLB_2025."""
        return cls(
            name=decode_name(record.get("Player", "")),
            team=record.get("Team", ""),
            position=record.get("Pos", ""),
            war=record.get("WAR"),
            age=record.get("Age"),
            awards=record.get("Awards", ""),
            games=record.get("G"),
            home_runs=record.get("HR"),
            batting_avg=record.get("BA"),
            on_base_pct=record.get("OBP"),
            slugging=record.get("SLG"),
            ops=record.get("OPS"),
        )


# ---------------------------------------------------------------------------
# GeminiModel
# ---------------------------------------------------------------------------


class GeminiModel:
    """Thin wrapper around the Gemini API used to retrieve clue text.

    Pulls facts about a player from outside our dataset.
    """

    def __init__(self, api_key: str | None = None, model_name: str | None = None):
        env = _load_env()
        self.api_key = api_key or env.get("API_KEY", "")
        self.model_name = model_name or env.get("GEMINI_MODEL", "gemini-3.6-flash")
        self._client = None  # lazy-initialized google.genai Client

    def _get_client(self):
        """Lazily create the genai client (kept out of __init__ for testability)."""
        if self._client is None:
            from google import genai

            self._client = genai.Client(api_key=self.api_key)
        return self._client

    def ask(self, prompt: str) -> str:
        """Send a prompt to Gemini and return the text response."""
        client = self._get_client()
        resp = client.models.generate_content(
            model=self.model_name, contents=prompt
        )
        return (resp.text or "").strip()


# ---------------------------------------------------------------------------
# ValidatorModel
# ---------------------------------------------------------------------------


class ValidatorModel:
    """Guards clues against leaking the player's name.

    On a leak, builds an explicit corrective prompt that re-prompts Gemini,
    naming the offending information and forbidding it.
    """

    def __init__(self, max_retries: int = 3):
        self.max_retries = max_retries

    def contains_name(self, clue_text: str, player_name: str) -> bool:
        """Return True if the clue leaks the player's name (full or any part).

        TODO: refine matching (accents, nicknames). Baseline: case-insensitive
        substring match on the full name and each name token.
        """
        if not clue_text or not player_name:
            return False
        text = clue_text.lower()
        if player_name.lower() in text:
            return True
        for token in player_name.lower().split():
            if len(token) > 2 and token in text:
                return True
        return False

    def build_correction_prompt(
        self, question: str, player_name: str, bad_answer: str
    ) -> str:
        """Build an explicit re-prompt telling Gemini not to mention the name."""
        return (
            "Your previous answer mentioned the player's name, which is not "
            f"allowed. Do NOT include '{player_name}' or any part of it.\n"
            f"Previous answer: {bad_answer}\n"
            f"Answer this question again without revealing the name: {question}"
        )

    @staticmethod
    def redact_name(clue_text: str, player_name: str) -> str:
        """Last-resort fallback: blank out the name if retries are exhausted."""
        result = clue_text
        for token in [player_name, *player_name.split()]:
            if len(token) > 2:
                result = result.replace(token, "[hidden]")
        return result


# ---------------------------------------------------------------------------
# Clue
# ---------------------------------------------------------------------------


class Clue:
    """Owns the 3 fixed clue questions and the validated clue loop."""

    # Short UI labels, index-aligned with CLUE_QUESTIONS below.
    CLUE_LABELS = [
        "Player Nickname",
        "College / High School",
        "Best Career Moment",
    ]

    CLUE_QUESTIONS = [
        "Does the player have a nickname? If so, what is it?",
        "What college or high school did the player attend?",
        "What is the player's best career moment?",
    ]

    def __init__(
        self,
        player: Player,
        gemini: GeminiModel | None = None,
        validator: ValidatorModel | None = None,
    ):
        self.player = player
        self.gemini = gemini or GeminiModel()
        self.validator = validator or ValidatorModel()

    def _build_prompt(self, question: str) -> str:
        """Compose the base prompt for a clue question."""
        return (
            f"You are giving a trivia clue about the MLB player {self.player.name}. "
            "Answer the following question factually and concisely. "
            f"Do NOT mention the player's name.\nQuestion: {question}"
        )

    def get_validated_clue(self, index: int) -> str:
        """Get clue `index`, re-prompting until the name is absent (Design.md loop).

        TODO: wire up once GeminiModel.ask is implemented.
        """
        question = self.CLUE_QUESTIONS[index]
        prompt = self._build_prompt(question)

        answer = self.gemini.ask(prompt)
        retries = 0
        while (
            self.validator.contains_name(answer, self.player.name)
            and retries < self.validator.max_retries
        ):
            correction = self.validator.build_correction_prompt(
                question, self.player.name, answer
            )
            answer = self.gemini.ask(correction)
            retries += 1

        if self.validator.contains_name(answer, self.player.name):
            answer = self.validator.redact_name(answer, self.player.name)
        return answer


