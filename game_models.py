"""Class scaffolding for the MLB Player Guessing Game.

See Design.md for the full design. The dataset (Data/MLB_2025) is used ONLY to
pick the secret player. All clues are generated by GeminiModel and screened by
ValidatorModel so a clue never leaks the player's name.

Classes:
    Player          - a single MLB player (name / team / position)
    GeminiModel     - thin wrapper around the Gemini API
    ValidatorModel  - detects name leaks and builds corrective re-prompts
    Clue            - owns the 3 fixed clue questions + the validated clue loop
    Game            - orchestrates a round: pick player, reveal clues, score
"""

from __future__ import annotations

import json
import os
import random
from dataclasses import dataclass, field


# ---------------------------------------------------------------------------
# Config
# ---------------------------------------------------------------------------

DATA_PATH = os.path.join(os.path.dirname(__file__), "Data", "MLB_2025")


def _load_env(path: str = ".env") -> dict:
    """Read a simple KEY = VALUE .env file (values may have surrounding spaces)."""
    env = {}
    full = os.path.join(os.path.dirname(__file__), path)
    if not os.path.exists(full):
        return env
    with open(full, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, value = line.split("=", 1)
            env[key.strip()] = value.strip()
    return env


