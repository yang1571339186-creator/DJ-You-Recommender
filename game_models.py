@dataclass
class Game:
    """Orchestrates one round: pick a secret player, reveal clues, score guesses."""

    data_path: str = DATA_PATH
    player_data: list = field(default_factory=list)
    all_names: list = field(default_factory=list)
    secret_player: Player | None = None
    clue: Clue | None = None
    clue_index: int = 0
    attempts: int = 0
    score: int = 0
    status: str = "playing"  # "playing" | "won" | "lost"

    MAX_CLUES = 3

    def __post_init__(self):
        if not self.player_data:
            self.load_data()

    def load_data(self) -> None:
        """Load Data/MLB_2025 into a list of records and cache all player names."""
        with open(self.data_path, "r", encoding="utf-8") as f:
            raw = json.load(f)
        self.player_data = list(raw.values())
        self.all_names = sorted(r.get("Player", "") for r in self.player_data)

    def all_teams(self) -> list:
        """Return the sorted unique team codes present in the data.

        A player's Team field may list several space-separated codes (traded
        mid-season, e.g. "BOS SFG"), so codes are split out individually.
        """
        codes = set()
        for record in self.player_data:
            codes.update(record.get("Team", "").split())
        return sorted(codes)

    def retrieve_player(
        self, team: str | None = None, awards: bool = False
    ) -> Player:
        """Pick a random secret player from the data.

        Optional filters:
            team    - only players whose Team field contains this team code.
            awards  - if truthy, only players with "AS" in their Awards field
                      (i.e. All-Stars).
        """
        candidates = self.player_data
        if team:
            candidates = [r for r in candidates if team in r.get("Team", "")]
        if awards:
            candidates = [r for r in candidates if "AS" in r.get("Awards", "")]

        if not candidates:
            raise ValueError("No players match the given filters.")

        record = random.choice(candidates)
        self.secret_player = Player.from_record(record)
        return self.secret_player

    def retrieve_guess(self, name: str) -> Player | None:
        """Look up a player by name and return a Player object.

        Unlike retrieve_player, this does NOT set self.secret_player. Returns
        None if no player with a matching name is found. Matching is
        case-insensitive on the full name.
        """
        target = name.strip().lower()
        for record in self.player_data:
            if record.get("Player", "").strip().lower() == target:
                return Player.from_record(record)
        return None

    def start_new_round(self, team: str | None = None, awards: bool = False) -> None:
        """Reset state and begin a new round.

        Filters (team, awards) are forwarded to retrieve_player to constrain
        which players can be chosen as the secret.
        """
        self.retrieve_player(team=team, awards=awards)
        self.clue = Clue(self.secret_player)
        self.clue_index = 0
        self.attempts = 0
        self.status = "playing"

    def get_clue(self, index: int) -> str:
        """Return the clue at a specific index (0-based), independent of order.

        Used when clues can be revealed individually rather than sequentially.
        """
        if index < 0 or index >= self.MAX_CLUES:
            return None
        return self.clue.get_validated_clue(index)

    def next_clue(self) -> str:
        """Return the next clue in sequence, or None if all are exhausted."""
        if self.clue_index >= self.MAX_CLUES:
            return None
        clue_text = self.clue.get_validated_clue(self.clue_index)
        self.clue_index += 1
        return clue_text

    def check_guess(self, name: str) -> bool:
        """Check a guessed name against the secret. Advances/ends the round.

        Clues are now revealed independently of guessing, so the round ends
        after MAX_CLUES wrong *attempts* rather than after all clues are used.
        Scoring still rewards guessing with fewer clues revealed.
        """
        self.attempts += 1
        correct = name.strip().lower() == self.secret_player.name.strip().lower()
        if correct:
            self.status = "won"
            self.score += self._score_for_clues_used()
        elif self.attempts >= self.MAX_CLUES:
            self.status = "lost"
        return correct

    def _score_for_clues_used(self) -> int:
        """Fewer clues used = more points."""
        return max(10, 100 - 30 * self.clue_index)

    def end_round(self) -> None:
        """Force-end the round (e.g. give up)."""
        self.status = "lost"


